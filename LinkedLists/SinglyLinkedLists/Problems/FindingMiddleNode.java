package Problems;

public class FindingMiddleNode {
    private static Node middleNode(LinkedList list){
        Node slow = list.head;
        Node fast = list.head;
        while(fast != null && fast.next != null){
            slow = slow.next;
            fast = fast.next.next;
        }
        return slow;
    }
    public static void main(String[] args){
        LinkedList list = new LinkedList();

        list.addLast(1);
        list.addLast(2);
        list.addLast(3);
        list.addLast(4);
        list.addLast(5);
        list.addLast(6);

        Node node = middleNode(list);

        System.out.println("Middle Node is: "+node.data);
    }
}

